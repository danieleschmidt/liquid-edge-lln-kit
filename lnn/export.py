"""Export LiquidNetwork weights as a C header file for embedded targets."""
import numpy as np
from .network import LiquidNetwork


def _array_to_c(arr: np.ndarray, name: str) -> str:
    """Render a 1-D or 2-D numpy array as a C initialiser."""
    arr = np.asarray(arr, dtype=float)
    if arr.ndim == 1:
        vals = ", ".join(f"{v:.8f}f" for v in arr)
        return f"float {name}[{arr.shape[0]}] = {{{vals}}};"
    elif arr.ndim == 2:
        rows = ", ".join(
            "{" + ", ".join(f"{v:.8f}f" for v in row) + "}"
            for row in arr
        )
        return f"float {name}[{arr.shape[0]}][{arr.shape[1]}] = {{{rows}}};"
    else:
        raise ValueError(f"Only 1-D and 2-D arrays supported, got shape {arr.shape}")


def export_c_header(network: LiquidNetwork, filename: str):
    """
    Write the weights of *network* to a C header file.

    Example output
    --------------
    // Auto-generated weights
    #define N_CELLS 2
    #define HIDDEN_DIM 4
    float W_in_0[4][1] = {{...}};
    float tau_0[4] = {...};

    Parameters
    ----------
    network : LiquidNetwork
    filename : str
        Path to the output .h file.
    """
    cells = network.cells
    n_cells = len(cells)
    hidden_dim = cells[0].hidden_dim

    lines = [
        "// Auto-generated weights — do not edit",
        "// Generated by liquid-edge-lln-kit",
        "",
        f"#define N_CELLS {n_cells}",
        f"#define HIDDEN_DIM {hidden_dim}",
        "",
    ]

    for i, cell in enumerate(cells):
        lines.append(f"// Cell {i}")
        lines.append(_array_to_c(cell.W_in,  f"W_in_{i}"))
        lines.append(_array_to_c(cell.W_rec, f"W_rec_{i}"))
        lines.append(_array_to_c(cell.tau,   f"tau_{i}"))
        lines.append(_array_to_c(cell.bias,  f"bias_{i}"))
        lines.append("")

    with open(filename, "w") as fh:
        fh.write("\n".join(lines))
